const DICT = { en, es, ca, fr, de };
let current = 'en';

export const getLang = () => current;
export function setLang(l) { current = DICT[l] ? l : 'en'; }

export function fill(s, params = {}) {
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

// Params may be { t: key } to nest a translated word (e.g. a piece name).
export function t(key, params = {}) {
  const p = {};
  for (const [k, v] of Object.entries(params)) p[k] = v && typeof v === 'object' && 't' in v ? t(v.t) : v;
  return fill(DICT[current][key] ?? en[key] ?? key, p);
}

